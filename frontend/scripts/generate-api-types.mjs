// Generate src/types/api.gen.ts from openapi.json (the backend's exported OpenAPI document).
// `npm run types:generate` runs this and then Prettier; `just types` refreshes openapi.json first.
import { writeFileSync } from 'node:fs'
import openapiTS, { astToString } from 'openapi-typescript'

const source = new URL('../openapi.json', import.meta.url)
const target = new URL('../src/types/api.gen.ts', import.meta.url)

// alphabetize: stable diffs. defaultNonNullable off: a request field with `default: null`
// stays optional for the client; response fields are required by the backend's ResponseModel.
const ast = await openapiTS(source, { alphabetize: true, defaultNonNullable: false })
const header =
  '// Generated by scripts/generate-api-types.mjs from openapi.json. Do not edit; run `just types`.\n'
writeFileSync(target, header + astToString(ast))
